CREATE TABLE Book (
bookid NUMBER(3) PRIMARY KEY,
bookname VARCHAR2(40),
publisher VARCHAR2(40),
price NUMBER(8)
);

CREATE TABLE Customer (
custid NUMBER(3) PRIMARY KEY,
name VARCHAR2(40),
address VARCHAR2(50),
phone VARCHAR2(20)
);

CREATE TABLE Orders (
orderid NUMBER(3) PRIMARY KEY,
custid NUMBER(3) REFERENCES Customer(custid),
bookid NUMBER(3) REFERENCES Book(bookid),
saleprice NUMBER(8),
orderdate DATE
);

