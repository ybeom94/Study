DROP TABLE emp;
DROP TABLE dept;

CREATE TABLE dept (
    deptno NUMBER(2) PRIMARY KEY,
    dname  VARCHAR2(20) NOT NULL,
    loc    VARCHAR2(20)
);

CREATE TABLE emp (
    empno    NUMBER(4) PRIMARY KEY,
    ename    VARCHAR2(20) NOT NULL,
    job      VARCHAR2(20),
    hiredate DATE DEFAULT SYSDATE,
    comm     NUMBER(10,2),
    sal      NUMBER(10,2),
    deptno   NUMBER(2),
    CONSTRAINT fk_emp_dept FOREIGN KEY (deptno)
    REFERENCES dept(deptno)
);

