package Part01_Java_Fundamentals;

/*
    Chapter 03. 연산자
 
    3.1 부호·증감 연산자
    - +와 -는 숫자의 부호를 나타낸다.
    - ++와 --는 변수 값을 1만큼 증감하며 전위형은 먼저 변경하고 후위형은 현재 값을 사용한 뒤 변경한다.
 
    3.2 산술 연산자
    - +, -, *, /, %는 기본 산술 연산에 사용한다.
    - 정수끼리 나누면 정수 몫을 구하고, 나머지 연산 %는 나누고 남은 값을 계산한다.
 
    3.3 오버플로우와 언더플로우
    - 정수 타입의 표현 범위를 넘으면 값이 순환하여 기대와 다른 결과가 나올 수 있다. 
    - Math.addExact 등은 일부 정수 오버플로우를 예외로 감지한다.
 
    3.4 정확한 계산은 정수 연산으로
    - 부동소수점 수는 이진 표현의 한계로 0.1 등을 정확히 표현하지 못할 수 있다.
    - 금액처럼 정확성이 필요하면 정수 단위 또는 BigDecimal 등 적절한 표현을 선택한다.
 
    3.5 나눗셈 연산 후 NaN과 Infinity 처리
    - 정수의 0 나눗셈은 ArithmeticException을 일으킨다.
    - 부동소수점 연산에는 Infinity와 NaN이 존재하며 Double.isInfinite/Double.isNaN으로 검사한다.
 
    3.6 비교 연산자
    - ==, !=, <, <=, >, >=는 비교 결과로 boolean을 생성한다.
    - 참조형의 ==는 객체의 동일성을 비교하며 String 내용 비교에는 equals를 사용한다.
 
    3.7 논리 연산자
    - &&는 양쪽이 참일 때, ||는 하나라도 참일 때 참이다.
    - &&와 ||는 결과가 정해지면 뒤 식을 실행하지 않는 단축 평가를 수행한다.
 
    3.8 비트 논리 연산자
    - &, |, ^, ~는 정수의 비트 단위 연산을 수행한다.
    - &는 각 비트 AND, |는 OR, ^는 XOR, ~는 반전을 의미한다.
 
    3.9 비트 이동 연산자
    - <<는 왼쪽, >>는 부호를 유지하며 오른쪽, >>>는 0을 채우며 오른쪽으로 이동한다.
    - 이동 거리와 타입의 비트 수를 고려해야 한다.
 
    3.10 대입 연산자
    - =는 오른쪽 값을 왼쪽 변수에 대입하며 +=, -=, *= 등의 복합 대입으로 계산과 대입을 결합할 수 있다.
    - 복합 대입은 필요한 내부 형변환 규칙이 일반 산술식과 다를 수 있다.
 
    3.11 삼항(조건) 연산자
    - 조건식 ? 참일때값 : 거짓일때값 형태로 한 표현식에서 두 값 중 하나를 선택한다.
    - if/else와 달리 식의 결과를 만든다.
 
    3.12 연산의 방향과 우선순위
    - 연산자마다 우선순위와 결합 방향이 있다.
    - 의미가 불명확해지는 식은 괄호로 계산 순서를 명시하는 것이 안전하다.
 */

public class Chapter03Operators {
    public static void main(String[] args) throws Exception {
        int a = 10, b = 3;
        System.out.println(a / b);               // 정수 나눗셈: 3
        System.out.println(a % b);               // 나머지: 1
        System.out.println(a > b && b > 0);      // 논리 연산: true
        System.out.println(a >= 10 ? "참" : "거짓");
    }
}
